export function getAllTranslations(): Translation[] {
  return translations;
}

export function getFeaturedTranslations(): Translation[] {
  return translations.filter((translation) => translation.featured);
}

export function getTranslationById(id: string): Translation | undefined {
  return translations.find((translation) => translation.id === id);
}

export function getTranslationsByTag(tag: string): Translation[] {
  return translations.filter((translation) => translation.tags.includes(tag));
}

export function getTranslationsByCategory(category: Translation['category']): Translation[] {
  return translations.filter((translation) => translation.category === category);
}

export function getAllTranslationTags(): string[] {
  const tags = new Set<string>();
  translations.forEach((translation) => {
    translation.tags.forEach((tag) => tags.add(tag));
  });
  return Array.from(tags).sort();
}

